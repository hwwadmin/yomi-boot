-- 平台共享 DDL：DTM 子事务屏障表（各领域库内各建一份，与业务表同库）
-- PostgreSQL 版；MySQL 版见 sql/mysql/barrier.sql，两份字段口径一致。
-- 与 cloud/dtm 封装口径一致，勿在各服务 script/sql 下复制。

CREATE TABLE IF NOT EXISTS sys_barrier (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    trans_type  VARCHAR(45)  NOT NULL DEFAULT '',
    gid         VARCHAR(128) NOT NULL DEFAULT '',
    branch_id   VARCHAR(128) NOT NULL DEFAULT '',
    op          VARCHAR(45)  NOT NULL DEFAULT '',
    barrier_id  VARCHAR(45)  NOT NULL DEFAULT '',
    reason      VARCHAR(45)  NOT NULL DEFAULT '',
    create_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uniq_barrier UNIQUE (trans_type, gid, branch_id, op, barrier_id)
);

COMMENT ON TABLE sys_barrier IS 'DTM 子事务屏障';
COMMENT ON COLUMN sys_barrier.reason IS 'rollback/timeout 等';
